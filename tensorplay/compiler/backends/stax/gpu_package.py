"""A deployment package for a region that runs on the GPU.

A package is a directory a caller can load without a compiler: it holds the
shared object its entry point lives in, the weights the region reads from its
surroundings, and a description of every buffer the entry point is handed.
The CPU package (see :mod:`aot_package`) writes one host translation unit that
calls the kernels the region was lowered to.  A GPU region has no host kernel
to call: its schedule is one or more compiled GPU kernels, each of which the
driver loads from a binary.  So a GPU package carries those binaries beside
the entry point, and the entry point loads and launches them from there.

What a package can describe is what the build could see.  Every kernel is
compiled once and its binary kept, so a package is written for the shapes it
was built with.  A kernel launched over a grid a package cannot work out, or
handed an argument it cannot describe, is refused rather than written as a
package that would launch the wrong thing.
"""

