def build_gpu_package(
    fn: Any,
    example_inputs: Sequence[Any],
    path: str,
    *,
    options: Optional[dict[str, bool]] = None,
    overwrite: bool = False,
) -> str:
    """Write ``fn`` for ``example_inputs`` as a GPU package under ``path``.

    The region is lowered for the device its inputs live on, run once so that
    its kernels are compiled, and then run again with its launches recorded.
    Each kernel's binary is copied into the package, and the entry point loads
    and launches them from there.  Returns the package directory.
    """

    if not callable(fn):
        raise TypeError(
            f"build_gpu_package() expected a callable, got {type(fn)!r}"
        )
    inputs = list(example_inputs)
    for value in inputs:
        if not isinstance(value, tp.Tensor):
            raise GpuPackageError(
                "a package takes tensor inputs; "
                f"{type(value).__name__} cannot be described"
            )
        if value.device.type != "cuda":
            raise GpuPackageError(
                "a GPU package is built from the device its inputs live on; "
                f"input lives on {value.device.type}"
            )
    if os.path.exists(path) and os.listdir(path) and not overwrite:
        raise GpuPackageError(f"{path} already holds a package; pass overwrite=True")

    from tensorplay.graph import Tracer
    from tensorplay.graph.passes import ShapeProp

    from . import backend as stax_backend

    graph_module = Tracer().trace(
        fn, sample_inputs={f"p{i}": value for i, value in enumerate(inputs)}
    )
    ShapeProp(inputs)(graph_module)
    stax_options = {"stax.cudagraphs": False}
    stax_options.update(options or {})
    from . import async_compile as acmod
    from . import config as stax_config

    # The region is built in this process so that every kernel it names is
    # here to be read: a kernel built in a worker is not, and a package has to
    # carry the binary the launch it records actually runs.
    previous_threads = stax_config.compile_threads
    stax_config.compile_threads = 1
    seen, original_triton = _recording_kernels()
    try:
        with tp.no_grad():
            compiled = stax_backend.stax(graph_module, inputs, options=stax_options)
    finally:
        acmod.AsyncCompile.triton = original_triton
        stax_config.compile_threads = previous_threads

    module_call = getattr(compiled, "_tensorplay_module_call", None)
    module = getattr(module_call, "__self__", None)
    if module is None:
        raise GpuPackageError(
            "the region has no generated module to deploy: it did not compile "
            "to a schedule this package can carry"
        )

    launches, results = _record_launches(compiled, inputs, seen)
    if not launches:
        raise GpuPackageError(
            "the region runs no GPU kernel, so there is nothing for a GPU "
            "package to load: its schedule was not lowered to device kernels "
            "and ran through the interpreter instead"
        )

    slots, by_pointer, output_order = _slot_table(inputs, launches, results)
    kernels, binaries = _kernel_specs(launches, by_pointer)

    spec = GpuPackageSpec(slots, kernels, (), "", output_order)
    header = _emit_gpu_header(spec)
    entry = _emit_gpu_entry_source()

    files = _package_paths(path)
    kernels_dir = os.path.join(path, KERNELS_DIR)
    os.makedirs(kernels_dir, exist_ok=True)
    for kernel, blob in zip(kernels, binaries):
        with open(os.path.join(kernels_dir, kernel.cubin), "wb") as handle:
            handle.write(blob)
    with open(files["header"], "w") as handle:
        handle.write(header)
    with open(files["entry"], "w") as handle:
        handle.write(entry)
    with open(files["metadata"], "w") as handle:
        json.dump(_metadata_payload(spec), handle, indent=2)
        handle.write("\n")

    options_cpp = _cpp_build_options()
    options_cpp.include_dirs = [
        *options_cpp.include_dirs,
        path,
        _CUDA_INCLUDE,
    ]
    options_cpp.library_dirs = [*options_cpp.library_dirs, _CUDA_LIB_DIR]
    options_cpp.libraries = [*options_cpp.libraries, "cuda"]
    builder = CppBuilder(
        name=MODEL_LIBRARY,
        sources=[files["entry"]],
        options=options_cpp,
        output_dir=path,
    )
    builder.build()
    return path


def _run_and_read(compiled: Any, inputs: Sequence[Any]) -> list[Any]:
    """Run the region once, and read its results as a list."""

    result = compiled(*inputs)
    return list(result) if isinstance(result, (tuple, list)) else [result]


def _outputs_of(
    compiled: Any, inputs: Sequence[Any], slots: Sequence[PackageSlot]
) -> dict[int, int]:
    """Which slot each of the region's results was written into, by address.

    The results come back in the order the table names them, so the pointer of
    each is matched with the slot it stands for.
    """

    values = _run_and_read(compiled, inputs)
    output_slots = [slot for slot in slots if slot.role == ROLE_OUTPUT]
    if len(values) != len(output_slots):
        raise GpuPackageError(
            f"the region returned {len(values)} results but its table names "
            f"{len(output_slots)}"
        )
    return {
        value.data_ptr(): slot.index
        for value, slot in zip(values, output_slots)
    }


def _metadata_payload(spec: GpuPackageSpec) -> dict:
    return {
        "slots": [
            {
                "index": slot.index,
                "name": slot.name,
                "role": slot.role,
                "shape": list(slot.shape),
                "stride": list(slot.stride),
                "dtype": slot.dtype,
                "itemsize": slot.itemsize,
                "device": slot.device,
                "offset": slot.offset,
                "nbytes": slot.nbytes,
            }
            for slot in spec.slots
        ],
        "kernels": [
            {
                "index": kernel.index,
                "name": kernel.name,
                "symbol": kernel.symbol,
                "cubin": kernel.cubin,
                "num_warps": kernel.num_warps,
                "shared": kernel.shared,
                "num_ctas": kernel.num_ctas,
                "grid": list(kernel.grid),
                "params": list(kernel.params),
                "ptr_slots": list(kernel.ptr_slots),
                "scalars": list(kernel.scalars),
            }
            for kernel in spec.kernels
        ],
        "sizevars": list(spec.sizevar_names),
        "outputs": list(spec.output_order),
    }


