def load_gpu_package(path: str):
    """Read a GPU package back, as a callable over this project's tensors."""

    files = _package_paths(path)
    for name in ("model", "metadata", "header", "entry"):
        if not os.path.exists(files[name]):
            raise GpuPackageError(
                f"{path} has no {os.path.basename(files[name])}"
            )

    with open(files["metadata"]) as handle:
        payload = json.load(handle)
    slots = payload.get("slots", [])
    kernels = payload.get("kernels", [])
    if not slots:
        raise GpuPackageError(f"{path} describes no buffers")

    library = ctypes.CDLL(files["model"])
    entry = library.aoti_entry
    entry.argtypes = [
        ctypes.POINTER(ctypes.c_void_p),
        ctypes.POINTER(ctypes.c_void_p),
        ctypes.POINTER(ctypes.c_long),
    ]
    entry.restype = ctypes.c_int
    set_constants = getattr(library, "aoti_set_constants", None)
    if set_constants is not None:
        set_constants.argtypes = [ctypes.POINTER(ctypes.c_void_p)]
        set_constants.restype = ctypes.c_int
        set_constants(None)
    set_kernels_dir = getattr(library, "aoti_set_kernels_dir", None)
    kernels_dir = os.path.join(path, KERNELS_DIR)
    if set_kernels_dir is not None:
        set_kernels_dir.argtypes = [ctypes.c_char_p]
        set_kernels_dir.restype = ctypes.c_int
        set_kernels_dir(kernels_dir.encode())

    inputs = [slot for slot in slots if slot["role"] == ROLE_INPUT]
    buffers = [slot for slot in slots if slot["role"] != ROLE_INPUT]
    output_order = list(payload.get("outputs", ()))
    num_sizevars = len(payload.get("sizevars", ()))

    class GpuModule:
        """A package, callable over tensors that live on the device."""

        def __call__(self, *args):
            if len(args) != len(inputs):
                raise GpuPackageError(
                    f"the package takes {len(inputs)} inputs, got {len(args)}"
                )
            input_ptrs = (ctypes.c_void_p * max(len(args), 1))()
            for index, value in enumerate(args):
                input_ptrs[index] = value.data_ptr()

            allocated = {}
            output_ptrs = (ctypes.c_void_p * max(len(buffers), 1))()
            for index, slot in enumerate(buffers):
                shape = tuple(int(s) for s in slot["shape"])
                stride = tuple(int(s) for s in slot["stride"])
                name = str(slot["dtype"]).rsplit(".", 1)[-1]
                dtype = tp.dtype(getattr(tp, name))
                value = tp.empty_strided(shape, stride, dtype=dtype, device="cuda")
                allocated[slot["index"]] = value
                output_ptrs[index] = value.data_ptr()

            sizevars = (ctypes.c_long * max(num_sizevars, 1))()
            status = entry(input_ptrs, output_ptrs, sizevars)
            if status != 0:
                raise GpuPackageError(
                    f"the package's entry point failed ({status})"
                )

            argument_of = {
                slot["index"]: position for position, slot in enumerate(inputs)
            }
            result = []
            for index in output_order:
                if index in argument_of:
                    # A region that answers with one of its arguments hands
                    # that argument back rather than filling a buffer.
                    result.append(args[argument_of[index]])
                else:
                    result.append(allocated[index])
            if len(result) == 1:
                return result[0]
            return tuple(result)

        @property
        def kernels(self):
            return tuple(kernel["name"] for kernel in kernels)

        @property
        def slots(self):
            return tuple(slots)

    #: Where the binaries this package launches were unpacked.
    GpuModule.kernels_dir = kernels_dir
    return GpuModule()