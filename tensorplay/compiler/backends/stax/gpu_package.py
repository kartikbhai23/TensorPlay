def _grid_for(result: Any, args: Sequence[Any]) -> tuple[int, int, int]:
    """The grid a launch was given, worked out from the kernel's configuration.

    Only the one-dimensional grid a pointwise kernel is launched over is
    described: the number of whole tiles its extent needs.  Anything else is
    refused rather than guessed at, because a wrong grid is a wrong answer.
    """

    meta = getattr(result, "tp_meta", {}) or {}
    if meta.get("grid_type") != "Grid1D":
        raise GpuPackageError(
            f"the kernel is launched with a {meta.get('grid_type')!r} grid, "
            "which a package cannot describe yet"
        )
    extent = None
    for value in args:
        if isinstance(value, int) and not isinstance(value, bool):
            extent = int(value)
    if extent is None:
        raise GpuPackageError(
            "the kernel is launched over an extent the build could not read"
        )
    tile = None
    config = getattr(result, "config", None)
    for entry in str(config).split(","):
        if ":" in entry and entry.split(":")[0].strip().endswith("BLOCK"):
            tile = int(entry.split(":")[1])
    if not tile:
        raise GpuPackageError(
            "the kernel's tile size was not among its configuration"
        )
    return ((extent + tile - 1) // tile, 1, 1)


def _recording_kernels():
    """Note every kernel the compiler builds, as it builds them.

    A generated region names its kernels when its module is written, so the
    note has to be in place before the region is compiled rather than after.
    """

    from . import async_compile as acmod

    seen: list[tuple[str, Any]] = []
    original = acmod.AsyncCompile.triton

    def recording(self, name, source_code, device_str="cuda"):
        kernel = original(self, name, source_code, device_str)
        seen.append((name, kernel))
        return kernel

    acmod.AsyncCompile.triton = recording
    return seen, original


def _record_launches(
    compiled: Any, sample: Sequence[Any], seen: Sequence[tuple[str, Any]]
) -> tuple[list[tuple[Any, list]], list[Any]]:
    """Run the region and note every kernel launch it makes.

    The kernels are compiled by the first run; the launches are recorded by a
    second.  That run also answers with the region's results, so the buffers
    the launches touched and the buffers the caller gets back are read from
    one and the same run: a later run would allocate storage of its own.
    """

    launches: list[tuple[Any, list]] = []
    restores = []
    for name, kernel in seen:
        original_run = kernel.run

        def recording_run(*args, _run=original_run, **kwargs):
            launches.append((kernel, list(args)))
            return _run(*args, **kwargs)

        kernel.run = recording_run
        restores.append((kernel, original_run))
    try:
        result = compiled(*sample)
    finally:
        for kernel, original_run in restores:
            kernel.run = original_run
    values = list(result) if isinstance(result, (tuple, list)) else [result]
    return launches, values


def _slot_table(
    inputs: Sequence[Any], launches: Sequence[tuple[Any, list]], results: Sequence[Any]
) -> tuple[tuple[PackageSlot, ...], dict[int, int], tuple[int, ...]]:
    """Describe every buffer a launch names, and which of them are results.

    A package is handed the region's arguments and asked to fill its results.
    The buffer a kernel writes is one the region allocated for itself, so the
    entry point has to be given it as well; the ones the caller gets back are
    the buffers the region answered with.  Returns the slots, the slot each
    address occupies, and the slots of the results in the order they are
    returned.
    """

    slots: list[PackageSlot] = []
    by_pointer: dict[int, int] = {}
    for index, value in enumerate(inputs):
        slots.append(_slot_of(index, f"input{index}", ROLE_INPUT, value))
        by_pointer[value.data_ptr()] = index

    result_pointers: list[int] = []
    for value in results:
        pointer = value.data_ptr()
        if pointer not in result_pointers:
            result_pointers.append(pointer)

    written: dict[int, Any] = {}
    for _kernel, args in launches:
        for value in args:
            if not hasattr(value, "data_ptr"):
                continue
            pointer = value.data_ptr()
            if pointer not in by_pointer:
                written.setdefault(pointer, value)

    for pointer in result_pointers:
        if pointer not in by_pointer and pointer not in written:
            raise GpuPackageError(
                "the region answered with a buffer none of its kernels wrote; "
                "a package can only describe storage its kernels reach"
            )

    outputs_seen = 0
    for pointer, value in written.items():
        index = len(slots)
        if pointer in result_pointers:
            role = ROLE_OUTPUT
            name = f"output{outputs_seen}"
            outputs_seen += 1
        else:
            role = ROLE_INTERMEDIATE
            name = f"buffer{index}"
        slots.append(_slot_of(index, name, role, value))
        by_pointer[pointer] = index

    order = tuple(by_pointer[pointer] for pointer in result_pointers)
    return tuple(slots), by_pointer, order


def _slot_of(index: int, name: str, role: str, value: Any) -> PackageSlot:
    dtype = value.dtype
    return PackageSlot(
        index=index,
        name=name,
        role=role,
        shape=tuple(int(s) for s in value.shape),
        stride=tuple(int(s) for s in value.stride()),
        dtype=str(dtype),
        dtype_code=int(dtype),
        itemsize=int(dtype.itemsize),
        device=str(value.device),
    )


def _ptx_params(asm: dict) -> list[str]:
    """What each parameter of the kernel's entry point is, from its own code.

    A kernel's Python spelling names the buffers it reads and the numbers it
    was given; the binary may declare more than that -- scratch the driver
    would otherwise have to size, and which a package that was built without
    any leaves unset.  The binary is what says how many parameters a launch
    hands over, so it is read rather than guessed at.
    """

    kinds: list[str] = []
    inside = False
    for line in (asm.get("ptx") or "").splitlines():
        if ".visible .entry" in line:
            inside = True
            continue
        if not inside:
            continue
        if ".param" in line:
            if ".ptr" in line:
                kinds.append("ptr")
            elif ".u32" in line or ".i32" in line:
                kinds.append("i32")
            else:
                kinds.append("i64")
        elif ")" in line:
            break
    return kinds


def _kernel_specs(
    launches: Sequence[tuple[Any, list]],
    by_pointer: dict[int, int],
) -> tuple[tuple[GpuKernel, ...], list[bytes]]:
    """Describe each kernel and the binary it is loaded from.

    ``by_pointer`` names the slot each buffer a launch hands over occupies,
    which is what turns a launch's arguments into the entry point's table
    lookups.
    """

    specs: list[GpuKernel] = []
    binaries: list[bytes] = []
    for index, (kernel, args) in enumerate(launches):
        results = list(getattr(kernel, "compile_results", ()) or ())
        if len(results) != 1:
            raise GpuPackageError(
                f"the kernel {getattr(kernel, 'name', index)!r} was compiled "
                f"{len(results)} ways, so which binary a package should carry "
                "is not settled"
            )
        compiled = results[0].kernel
        meta = compiled.metadata
        asm = getattr(compiled, "asm", {}) or {}
        if "cubin" not in asm:
            raise GpuPackageError(
                "the kernel was compiled without a binary a package can load"
            )

        params: list[int] = []
        ptr_slots: list[int] = []
        scalars: list[int] = []
        declared = _ptx_params(asm)
        for value in args:
            if hasattr(value, "data_ptr"):
                params.append(KIND_POINTER)
                pointer = value.data_ptr()
                slot = by_pointer.get(pointer)
                if slot is None:
                    raise GpuPackageError(
                        f"a launch reads a buffer at {pointer} that the table "
                        "does not describe"
                    )
                ptr_slots.append(slot)
            elif isinstance(value, int) and not isinstance(value, bool):
                params.append(KIND_INT)
                scalars.append(int(value))
            else:
                raise GpuPackageError(
                    "a kernel takes an argument a package cannot describe: "
                    f"{type(value).__name__}"
                )

        # A kernel may declare parameters its Python spelling does not name;
        # they are given nothing, which is what a package built without
        # scratch means.  A kernel that declares fewer than it was handed is
        # refused, because the extra arguments would be read past its list.
        if len(declared) < len(params):
            raise GpuPackageError(
                f"the kernel {getattr(kernel, 'name', index)!r} declares "
                f"{len(declared)} parameters but was launched with "
                f"{len(params)}"
            )
        for declared_kind in declared[len(params):]:
            params.append(KIND_NULL)

        specs.append(
            GpuKernel(
                index=index,
                name=str(getattr(kernel, "name", f"kernel{index}")),
                symbol=str(meta.name),
                cubin=f"{index}_{meta.name}.cubin",
                num_warps=int(meta.num_warps),
                shared=int(meta.shared),
                num_ctas=int(meta.num_ctas),
                grid=_grid_for(results[0], args),
                params=tuple(params),
                ptr_slots=tuple(ptr_slots),
                scalars=tuple(scalars),
            )
        )
        binaries.append(bytes(asm["cubin"]))
    return tuple(specs), binaries


