#: What each argument of a launch is: a buffer the entry point's table names,
#: or a number that stands in the call.
KIND_POINTER = 0
KIND_INT = 1
#: A parameter the launch is given nothing for: the kernel declares it, and
#: what it stands for -- scratch the driver would otherwise have to size --
#: was not needed when the package was built.
KIND_NULL = 2

#: The warp size every NVIDIA device has used.  A package is written for the
#: device it was built on, and this is the width its launches are given.
_WARP_SIZE = 32

_CUDA_INCLUDE = "/usr/local/cuda/include"
_CUDA_LIB_DIR = "/usr/lib/x86_64-linux-gnu"


class GpuPackageError(PackageError):
    """A region cannot be written as a GPU package."""


@dataclass(frozen=True)
class GpuKernel:
    """One kernel the entry point loads and launches.

    ``symbol`` is the name the binary exports, ``params`` what each argument
    of the launch is, and ``ptr_slots`` which slot of the entry point's table
    each pointer argument names.  ``scalars`` are the values the number
    arguments carry, worked out when the package was built, so a package
    written from concrete shapes needs nothing but its buffers.
    """

    index: int
    name: str
    symbol: str
    cubin: str
    num_warps: int
    shared: int
    num_ctas: int
    grid: tuple[int, int, int]
    params: tuple[int, ...]
    ptr_slots: tuple[int, ...]
    scalars: tuple[int, ...]


@dataclass(frozen=True)
class GpuPackageSpec:
    """What a GPU package contains, as data."""

    slots: tuple[PackageSlot, ...]
    kernels: tuple[GpuKernel, ...]
    sizevar_names: tuple[str, ...]
    source_digest: str
    output_order: tuple[int, ...]

    @property
    def inputs(self) -> tuple[PackageSlot, ...]:
        return tuple(slot for slot in self.slots if slot.role == ROLE_INPUT)

    @property
    def outputs(self) -> tuple[PackageSlot, ...]:
        return tuple(slot for slot in self.slots if slot.role == ROLE_OUTPUT)


